ALTER DATABASE CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_bin;

CREATE TABLE users (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    username VARCHAR(128) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NULL
);

CREATE TABLE datasets (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT UNSIGNED NULL,
    FOREIGN KEY (user_id) REFERENCES users(id),
    name VARCHAR(255) NOT NULL,
    application_count INT UNSIGNED NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE responses (
    dataset_id BIGINT UNSIGNED NOT NULL,
    app_id VARCHAR(128) NOT NULL,
    before_json JSON NOT NULL,
    after_json JSON NOT NULL,
    PRIMARY KEY (dataset_id, app_id),
    FOREIGN KEY (dataset_id) REFERENCES datasets(id) ON DELETE CASCADE
);

CREATE TABLE configurations (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT UNSIGNED NULL,
    FOREIGN KEY (user_id) REFERENCES users(id),
    settings JSON NOT NULL
);

CREATE TABLE runs (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    user_id BIGINT UNSIGNED NULL,
    FOREIGN KEY (user_id) REFERENCES users(id),
    dataset_id BIGINT UNSIGNED NOT NULL,
    FOREIGN KEY (dataset_id) REFERENCES datasets(id),
    configuration_id BIGINT UNSIGNED NOT NULL,
    FOREIGN KEY (configuration_id) REFERENCES configurations(id),
    status ENUM('CREATED','QUEUED','RUNNING','SUCCEEDED','FAILED') NOT NULL DEFAULT 'CREATED',
    stage VARCHAR(32) NOT NULL DEFAULT 'created',
    processed INT UNSIGNED NOT NULL DEFAULT 0,
    error TEXT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX (status, id)
);

CREATE TABLE run_logs (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    run_id BIGINT UNSIGNED NOT NULL,
    FOREIGN KEY (run_id) REFERENCES runs(id) ON DELETE CASCADE,
    stage VARCHAR(32) NOT NULL,
    message TEXT NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    INDEX (run_id, id)
);

CREATE TABLE run_apps (
    run_id BIGINT UNSIGNED NOT NULL,
    APP_ID VARCHAR(128) NOT NULL,
    DIFF_FLAG BOOLEAN NOT NULL,
    DECISION_CHANGED BOOLEAN NOT NULL,
    segment JSON NOT NULL,
    PRIMARY KEY (run_id, APP_ID),
    FOREIGN KEY (run_id) REFERENCES runs(id) ON DELETE CASCADE,
    INDEX (run_id, DIFF_FLAG),
    INDEX (run_id, DECISION_CHANGED)
);

CREATE TABLE normalized (
    run_id BIGINT UNSIGNED NOT NULL,
    APP_ID VARCHAR(128) NOT NULL,
    SOURCE ENUM('BEFORE','AFTER') NOT NULL,
    PATH VARCHAR(384) NOT NULL,
    ARRAY_KEY VARCHAR(192) NOT NULL,
    PREFIX VARCHAR(384) NOT NULL,
    CLASS VARCHAR(384) NOT NULL,
    SUFFIX VARCHAR(384) NOT NULL,
    `KEY` VARCHAR(384) NOT NULL,
    VALUE TEXT NOT NULL,
    ADJUSTED_VALUE TEXT NOT NULL,
    PRIMARY KEY (run_id, APP_ID, SOURCE, PATH, ARRAY_KEY),
    FOREIGN KEY (run_id, APP_ID) REFERENCES run_apps(run_id, APP_ID) ON DELETE CASCADE
);

CREATE TABLE comparisons (
    run_id BIGINT UNSIGNED NOT NULL,
    APP_ID VARCHAR(128) NOT NULL,
    PATH VARCHAR(384) NOT NULL,
    ARRAY_KEY VARCHAR(192) NOT NULL,
    PREFIX VARCHAR(384) NOT NULL,
    CLASS VARCHAR(384) NOT NULL,
    SUFFIX VARCHAR(384) NOT NULL,
    `KEY` VARCHAR(384) NOT NULL,
    VALUE_BEFORE TEXT NULL,
    VALUE_AFTER TEXT NULL,
    ADJUSTED_BEFORE TEXT NULL,
    ADJUSTED_AFTER TEXT NULL,
    DIFF_FLAG BOOLEAN NOT NULL,
    CHANGE_TYPE ENUM('SAME','VALUE_CHANGED','ATTRIBUTE_NEW','ATTRIBUTE_LOST') NOT NULL,
    PRIMARY KEY (run_id, APP_ID, PATH, ARRAY_KEY),
    FOREIGN KEY (run_id, APP_ID) REFERENCES run_apps(run_id, APP_ID) ON DELETE CASCADE,
    INDEX (run_id, PATH, DIFF_FLAG),
    INDEX (run_id, CHANGE_TYPE),
    INDEX (run_id, DIFF_FLAG)
);

CREATE TABLE check_results (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    run_id BIGINT UNSIGNED NOT NULL,
    FOREIGN KEY (run_id) REFERENCES runs(id) ON DELETE CASCADE,
    check_id VARCHAR(128) NOT NULL,
    result JSON NOT NULL,
    INDEX (run_id, id)
);

CREATE TABLE run_summaries (
    run_id BIGINT UNSIGNED PRIMARY KEY,
    FOREIGN KEY (run_id) REFERENCES runs(id) ON DELETE CASCADE,
    applications INT UNSIGNED NOT NULL,
    apps_with_differences INT UNSIGNED NOT NULL,
    apps_with_decision_change INT UNSIGNED NOT NULL,
    comparison_rows INT UNSIGNED NOT NULL
);

CREATE TABLE pivot_facts (
    id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
    run_id BIGINT UNSIGNED NOT NULL,
    FOREIGN KEY (run_id) REFERENCES runs(id) ON DELETE CASCADE,
    PREFIX VARCHAR(384) NOT NULL,
    CLASS VARCHAR(384) NOT NULL,
    SUFFIX VARCHAR(384) NOT NULL,
    ARRAY_KEY VARCHAR(192) NOT NULL,
    `KEY` VARCHAR(384) NOT NULL,
    VALUE_ADJUSTED TEXT NOT NULL,
    DIFF_FLAG BOOLEAN NOT NULL,
    SOURCE ENUM('BEFORE','AFTER') NOT NULL,
    CNT INT UNSIGNED NOT NULL,
    INDEX (run_id, id)
);
